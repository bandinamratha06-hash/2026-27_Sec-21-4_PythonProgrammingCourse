# String
s = "  Hello Python World  "

print("Original String:", s)

# Uppercase
print("Uppercase:", s.upper())

# Lowercase
print("Lowercase:", s.lower())

# Strip
print("Strip:", s.strip())

# Split
print("Split:", s.split())

# Join
words = ["Hello", "Python"]
print("Join:", " ".join(words))

# Replace
print("Replace:", s.replace("Python", "Java"))

# Find
print("Find:", s.find("Python"))
