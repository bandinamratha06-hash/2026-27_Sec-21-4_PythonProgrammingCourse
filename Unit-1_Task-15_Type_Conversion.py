# Demonstrating type conversion in Python
# String to Integer
a = int(input("enter a num1"))
b = int(a)
print("String to Integer:", b, type(b))
# Integer to Float
c = int(input("enter a num2"))
d = float(c)
print("Integer to Float:", d, type(d))
# Float to Integer
e = float(input("enter a flout num"))
f = int(e)
print("Float to Integer:", f, type(f))
# Integer to String
g = int(input("enter a num"))
h = str(g)
print("Integer to String:", h, type(h))
# Float to String
i = float(input("enter a num"))
